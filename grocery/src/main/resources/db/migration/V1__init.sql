-- 엔티티 매핑 기준 초기 스키마 (2026-11-16)
-- enum 컬럼은 VARCHAR만 두고 허용 값 CHECK는 걸지 않는다 (값 검증은 Java enum이 담당)

CREATE TABLE users (
                       user_id    BIGINT GENERATED BY DEFAULT AS IDENTITY,
                       email      VARCHAR(255) NOT NULL,
                       password   VARCHAR(255) NOT NULL,
                       nickname   VARCHAR(50)  NOT NULL,
                       created_at TIMESTAMPTZ  NOT NULL,
                       updated_at TIMESTAMPTZ  NOT NULL,
                       CONSTRAINT pk_users PRIMARY KEY (user_id),
                       CONSTRAINT uk_users_email UNIQUE (email)
);

CREATE TABLE households (
                            household_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
                            name         VARCHAR(50) NOT NULL,
                            created_at   TIMESTAMPTZ NOT NULL,
                            updated_at   TIMESTAMPTZ NOT NULL,
                            CONSTRAINT pk_households PRIMARY KEY (household_id)
);

CREATE TABLE household_members (
                                   household_member_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
                                   household_id        BIGINT      NOT NULL,
                                   user_id             BIGINT      NOT NULL,
                                   role                VARCHAR(20) NOT NULL,
                                   joined_at           TIMESTAMPTZ NOT NULL,
                                   CONSTRAINT pk_household_members PRIMARY KEY (household_member_id),
                                   CONSTRAINT uk_household_members_household_user UNIQUE (household_id, user_id),
                                   CONSTRAINT fk_household_members_household
                                       FOREIGN KEY (household_id) REFERENCES households (household_id),
                                   CONSTRAINT fk_household_members_user
                                       FOREIGN KEY (user_id) REFERENCES users (user_id)
);
CREATE INDEX idx_household_members_user_id ON household_members (user_id);

CREATE TABLE foods (
                       food_id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
                       household_id       BIGINT,
                       created_by_user_id BIGINT,
                       name               VARCHAR(100) NOT NULL,
                       category           VARCHAR(30)  NOT NULL,
                       quantity_type      VARCHAR(20)  NOT NULL,
                       default_unit       VARCHAR(20)  NOT NULL,
                       source_type        VARCHAR(30)  NOT NULL,
                       active             BOOLEAN      NOT NULL DEFAULT TRUE,
                       created_at         TIMESTAMPTZ  NOT NULL,
                       updated_at         TIMESTAMPTZ  NOT NULL,
                       CONSTRAINT pk_foods PRIMARY KEY (food_id),
                       CONSTRAINT fk_foods_household
                           FOREIGN KEY (household_id) REFERENCES households (household_id),
                       CONSTRAINT fk_foods_created_by_user
                           FOREIGN KEY (created_by_user_id) REFERENCES users (user_id)
);
CREATE INDEX idx_foods_household_id ON foods (household_id);

CREATE TABLE food_stocks (
                             food_stock_id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
                             household_id      BIGINT        NOT NULL,
                             food_id           BIGINT        NOT NULL,
                             initial_quantity  NUMERIC(12,3) NOT NULL,
                             current_quantity  NUMERIC(12,3) NOT NULL,
                             unit              VARCHAR(20)   NOT NULL,
                             quantity_accuracy VARCHAR(20)   NOT NULL,
                             purchased_at      DATE,
                             expires_at        DATE,
                             opened_at         TIMESTAMPTZ,
                             storage_type      VARCHAR(30)   NOT NULL,
                             acquisition_type  VARCHAR(30)   NOT NULL,
                             product_label     VARCHAR(100),
                             memo              VARCHAR(500),
                             depleted_at       TIMESTAMPTZ,
                             depletion_reason  VARCHAR(30),
                             version           BIGINT        NOT NULL DEFAULT 0,
                             created_at        TIMESTAMPTZ   NOT NULL,
                             updated_at        TIMESTAMPTZ   NOT NULL,
                             CONSTRAINT pk_food_stocks PRIMARY KEY (food_stock_id),
                             CONSTRAINT fk_food_stocks_household
                                 FOREIGN KEY (household_id) REFERENCES households (household_id),
                             CONSTRAINT fk_food_stocks_food
                                 FOREIGN KEY (food_id) REFERENCES foods (food_id)
);
CREATE INDEX idx_food_stocks_household_expires_at ON food_stocks (household_id, expires_at);
CREATE INDEX idx_food_stocks_food_id ON food_stocks (food_id);

CREATE TABLE stock_histories (
                                 stock_history_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
                                 food_stock_id    BIGINT        NOT NULL,
                                 actor_user_id    BIGINT        NOT NULL,
                                 type             VARCHAR(20)   NOT NULL,
                                 before_quantity  NUMERIC(12,3),
                                 change_quantity  NUMERIC(12,3),
                                 after_quantity   NUMERIC(12,3),
                                 change_accuracy  VARCHAR(20),
                                 after_accuracy   VARCHAR(20),
                                 occurred_at      TIMESTAMPTZ   NOT NULL,
                                 created_at       TIMESTAMPTZ   NOT NULL,
                                 CONSTRAINT pk_stock_histories PRIMARY KEY (stock_history_id),
                                 CONSTRAINT fk_stock_histories_food_stock
                                     FOREIGN KEY (food_stock_id) REFERENCES food_stocks (food_stock_id),
                                 CONSTRAINT fk_stock_histories_actor_user
                                     FOREIGN KEY (actor_user_id) REFERENCES users (user_id)
);
CREATE INDEX idx_stock_histories_stock_occurred_at ON stock_histories (food_stock_id, occurred_at);
CREATE INDEX idx_stock_histories_actor_user_id ON stock_histories (actor_user_id);